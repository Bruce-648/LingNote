    internal const string DirectTranscriptRules = """
        【输入类型：录音转写】
        本次没有课堂笔记。录音转写只是识别主题、范围、重点与具体约定的线索，不是需要逐句复述的材料。先从标题和转写判断实际知识主题，再围绕该主题独立整理知识，补齐主题内缺少的核心知识点；不要机械沿用转写中的顺序、误识别或错误。没有依据确定主题时说明材料不足，不虚构。
