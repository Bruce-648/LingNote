    internal const string ClassroomRules = CommonRules + "\n\n" + ClassroomTaskRules;
    internal const string EnhancementRules = CommonRules + "\n\n" + EnhancementTaskRules;
    internal const string ClassroomCacheKey = ClassroomRules + ClassroomTemplate + ClassroomMergeTemplate;
    internal const string EnhancementCacheKey = EnhancementRules + EnhancementTemplate + OutlineTemplate + EnhancementMergeTemplate;

    private static string Fill(string template, Dictionary<string, string> values) =>
        System.Text.RegularExpressions.Regex.Replace(template, @"\{\{([^{}]+)\}\}", match => values[match.Groups[1].Value]);

    internal static string Segment(bool enhance, string title, int index, int count, string material, string? outline = null, bool fromTranscript = false)
    {
        var template=enhance ? EnhancementTemplate : ClassroomTemplate;
        if(enhance&&fromTranscript)template=template.Replace("<课堂笔记>","<录音转写>").Replace("</课堂笔记>","</录音转写>");
        var result = Fill(template, new()
        {
            ["课程标题"] = title, ["分段序号"] = index.ToString(), ["总段数"] = count.ToString(),
            ["当前转写分段"] = material, ["当前课堂笔记分段"] = material,
            ["例子要求"] = count == 1 ? "整篇例子为 0–2 个，可以自拟；不另写课程或整理说明。" : (index == 1 ? "这是第一个分段：整理本段知识，并参考全文标题索引补齐主题内明显缺少的核心知识点；索引中已有的其他章节交给对应分段。" : "这是后续分段：围绕本段主题整理并补齐必要知识，不重复全文索引中属于其他分段的章节。") + "分段稿不另写例子；合并全文时统一选取至多 2 个例子。"
        });
        if (enhance && !string.IsNullOrWhiteSpace(outline))
            result += "\n\n" + Fill(OutlineTemplate, new() { ["从当前课堂笔记提取的真实标题列表"] = outline });
        return result;
    }

    internal static string Merge(bool enhance, string outline, string material, int exampleLimit = 2, bool whole = true) =>
        Fill(enhance ? EnhancementMergeTemplate : ClassroomMergeTemplate, new()
        {
            ["主题索引"] = outline, ["当前批次课堂笔记分段稿"] = material,
            ["当前批次完善笔记分段稿"] = material, ["例子上限"] = exampleLimit.ToString(),
            ["知识补充要求"] = whole ? "结合完整分段稿判断主题，补齐主题内明显缺少的核心知识点；不扩写邻近主题。" : "只补充本批知识的必要条件与联系，不根据索引猜写其他批次正文。"
        });
